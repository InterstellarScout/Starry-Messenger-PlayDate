#### Story: A Strange Home for Strange Ideas

So, welcome to my home.

We are aboard the ferryboat Vallejo, which is tied up at the north end of Sausalito, close to San Francisco, and this is where I live.

And you may think this place is rather weird. That’s because I’ve always loved weird things. I remember when I was a little boy, people used to say to me, “Alan, you’re so weird. Why can’t you be like other people?”

Well, I thought that was just plain dull, like having the same thing for dinner every day. And, as is well said, variety is the spice of life.

So you will indeed find this place rather strange.

And some of the things that are weird are weird because they are just obvious, and nobody ever thinks of them. Some of the most fascinating scientific discoveries have been made by people who called ordinary common sense into question.

Like: anybody can see that the Earth is flat, and people know it’s flat. Calling that fundamental assumption into question is really the beginning of geography.

#### Story: The Weirdest Thing of All — Nothing

And when I think over the weirdest of all things I can think of, you know what it is?

Nothing.

The whole idea of nothing is something that has bugged people for centuries, especially in the West, because we have a saying in Latin: ex nihilo nihil fit, which means that out of nothing comes nothing.

You can’t, in other words, get something out of nothing.

And it’s occurred to me that this is a fallacy of tremendous proportions that lies at the root of all our common sense—not only in the West, but in many parts of the East as well.

And it comes up as a kind of terror of nothing: a put-down on nothing, on everything to do with nothing, everything associated with nothing, such as sleep, passivity, rest.

And even the feminine principle is often equated with the negative principle. Although women’s liberation people don’t like that kind of thing, when they get through understanding what I’m going to tell you, I don’t think they’ll object.

Because what has struck me is that nothing—the negative, the empty—is exceedingly powerful.

I would say not ex nihilo nihil fit, “out of nothing comes nothing,” but I would say:

You can’t have something without nothing.

#### Story: The Cigar in One Hand and Nothing in the Other

So how do we basically begin to think about the difference between something and nothing?

I can say there is a cigar in my right hand, and there is no cigar in my left hand. And so we get the idea of “is” here, and “isn’t,” or empty, here.

But behind that, of course, lies the far more obvious contrast of solid and space.

#### Story: Why Empty Space Makes Solid Things Visible

Now, we tend to think of space as nothing.

When we talk about the “conquest of space,” there’s a little element, notice, of hostility in that phrase. But actually, we’re talking about the conquest of distance.

Space as such—that is to say, whatever it is that lies between the Earth and the Moon, and the Earth and the Sun—is considered, especially since the Michelson–Morley experiment which showed there was no ether, to be just nothing at all.

But to suggest how very powerful and important this “nothing at all” is, let me point out to you that if you didn’t have space, you couldn’t have anything solid to begin with.

Without space outside the solid, you wouldn’t know where the solid’s edges were.

For example, you can see me on the camera because you see a background here, all around me, and that background shows up my outline.

But if that wasn’t there, then you would notice, say, only the beads and the microphone here, and this would become the background.

But you always have to have a background to see a figure. You just can’t do without it.

So that means that the figure and the ground, the solid and the space, in some way are inseparable and go together.

#### Story: The Magnet That Cannot Have Only One Pole

Now, we find this very commonly in the phenomena of magnetism and electricity.

A magnet has a north pole and a south pole, and a battery has a positive pole and a negative pole.

There is no such thing as a magnet with one pole only.

Supposing we equate north with “is” and south with “isn’t.” Then we see we can’t do without the two of them. You can chop the magnet in two, supposing it’s a bar magnet, and you’ll just get another north pole and south pole on the end of each piece.

And so, in the same way, a current will not flow through an electric circuit until the negative pole is connected as well as the positive.

#### Story: Hamlet Asked the Wrong Question

There isn’t a sort of fight between something and nothing.

You know the famous words of Hamlet: “To be or not to be, that is the question.”

It isn’t.

“To be or not to be” is not the question.

Because you can’t have a solid without space. Therefore, you can’t have an “is” without an “isn’t,” a something without a nothing, a figure without a background.

And we can turn that right the other way around and say you can’t have space without solid.

Because imagine nothing but space. Space, space, space, with nothing in it at all forever.

But there you are imagining it, and you’re something in it.

To have the whole idea of there being only space and nothing else at all is not only inconceivable, but perfectly meaningless.

Because we always know what we mean by contrasts.

We know what we mean by white in comparison with black. We know life in comparison with death. We know pleasure in comparison with pain, up in comparison with down.

But you will notice, of all these things, that they must come into being together.

You don’t have first something and then nothing, or first nothing and then something.

Something and nothing are two sides of the same coin.

#### Story: Filing Away One Side of a Coin

And, as you know, if you take a coin and you file away the tail side of it, and you file that side of it away completely, the head side will disappear as well.

So, in this sense, the positive and the negative, the something and the nothing, are inseparable. They go together.

And in this way you could say that the nothing is the force whereby the something can be manifested.

Without space, we couldn’t see the stars.

#### Story: Is a Tree Made of Wood?

Now, ordinarily, we think that what is basic to the physical world is something we call matter. And then matter has various shapes.

We think of tables as made of wood. We think of pots as made of clay.

But I ask you: is a tree made of wood in the same way as a table is?

Now, that would be stupid, wouldn’t it?

Because a tree is wood. It isn’t made of wood. “Wood” and “tree” are two different names for the same thing.

But there’s, in the back of our mind, the notion, as a root of common sense, that everything in the world is made of something—made of some kind of basic stuff.

#### Story: Looking for the “Stuff” the Universe Is Made Of

And physicists through the centuries have, of course, wanted to know what that was.

And physics began as a quest to discover the basic stuff out of which the world is made.

And with all our advances in physics, we’ve never found it.

What we have found is not stuff, but form.

We have found shapes. We have found structures.

Because when you turn up the microscope and you look at things where you thought there was some sort of stuff, you find instead form, pattern, structure.

You find the shapes of crystals, and you go in beyond the shapes of crystals and you find molecules. You go in beyond molecules and you find atoms. You go in beyond atoms and you find electrons and positrons, between which there are vast spaces.

And we can’t make up our minds, as to these electrons, whether they’re waves or whether they’re particles, and so we call them “wavicles.”

But they’re very tiny.

And if you want to ask, “What stuff are electrons made of?” we might be able to make a further analysis, but what we will come up with will never be stuff.

It will always be a pattern—a moving pattern which can be described and measured.

But we never get to any stuff, for the simple reason that there isn’t any.

#### Story: “Stuff” Is What Things Look Like When They Are Out of Focus

You see, what “stuff” actually is, is when you see something unclearly or out of focus. It becomes fuzzy.

You know, we say “stuffing” in something, like kapok in a cushion, or stuff like clay, because when we look at it with the naked eye it looks just like goo.

We can’t make out any significant shape to it.

But then, when you put it down under the microscope, you suddenly see shapes. It comes into clear focus as shape.

And you can go on and on and on looking into the nature of the world, and you will never find anything except form.

#### Story: Form and Emptiness Go Together

Well, what else is there besides form in the world?

Obviously, between the significant shapes of any form there is space.

And space and form, in that sense, go together as the fundamental things we’re dealing with in this universe.

And that’s why there’s a Buddhist saying—really, the whole of Buddhism is based on this saying—which is:

“That which is void is precisely form, and that which is form is precisely void.”

#### Story: The Two Meanings Hidden Inside “Clarity”

When you use the word clarity, what do you mean by clarity?

It might be a perfectly polished lens or mirror, or a clear day when there’s no smog and the air is perfectly transparent, like space.

The next thing you think of is form in clear focus—all the details articulate and perfect.

So the one word clarity suggests two apparently completely opposite things: the clarity of the lens or the mirror, and the clarity of articulate form.

And it is in this sense that the Buddhists say: “Form is void; void is form.”

Or we could put it another way. Instead of saying “is,” we could say “implies,” or the word that I invented: “goeswith,” spelled all in one.

Like a front goes with a back. A male goes with a female, and so on.

So form always goes with void.

#### Story: Why the Floor Is “Going Too Fast” to Fall Through

Form, indeed, is inseparable from the idea of energy.

And frisky form, especially when it’s moving in a very circumscribed area, appears to us as solid.

In the same way, for example, when you spin an electric fan, the empty spaces between the blades sort of disappear into a blur, and you can’t push a pencil, much less your finger, through the fan.

So in the same way, you can’t push your finger through the floor because the floor is going too fast.

But basically, what you have down there is nothing except nothing and form in motion.

#### Story: Light and Sound Exist by Turning On and Off

Now, we all know that energy is always vibration, pulsation.

Whether it be the energy of light or the energy of sound, it’s always on and off.

And in the case of light, say you get very fast light, very strong light—even, say, with alternating current—you don’t notice the discontinuity because your retina retains the impression of the “on” pulse.

And it’s exactly the same thing with sound.

When you hear a high note, it seems much more continuous. That’s because the vibrations are faster than a low note.

On a low note you can hear a kind of graininess, and that graininess is because you are hearing the rapid alternations of on and off.

#### Story: There Can Be No Wave Crest Without a Trough

When we think of waves and talk about waves, we think about the crests.

But isn’t it obvious that you cannot have the ups without the downs?

You cannot have the emphasis called a crest without the de-emphasis called the trough. They necessarily go with one another.

So, to have anything standing out, there must be, as it were, something standing down or standing back.

#### Story: Silence Is Part of Every Sound

When sound comes upon your ear, the eardrum vibrates.

When the “on” pulse of the sound comes, the eardrum is driven in a little. When the “off” succeeds, the eardrum comes out again, and the eardrum wiggles.

If you just pushed it in uniformly and left it there, you wouldn’t hear anything.

In the same way, if there is no sound and the eardrum is not being pushed at all, you have silence.

But to have sound, you must have the alternation of sound, silence, sound, silence, sound, silence.

#### Story: Existence as “Now You See It, Now You Don’t”

We shouldn’t really contrast existence with non-existence, because actually existence is the alternation of to be and not to be, of positive and negative, of on and off.

So you could say existence is eternal, if we are to consider existence as this alternation of: now you see it, now you don’t.

It is that contrast that presents the sensation of there being anything at all.

#### Story: The Fast and Slow Waves of the Universe

In light and sound, these waves are extraordinarily rapid, so that we don’t hear the interval between them.

But there are other circumstances in which the waves are extraordinarily slow, as in the alternation of day and night, light and darkness, and the much vaster alternations of life and death, of the great slow cycles of the world.

But these alternations are just as necessary to the being of the universe as in the very fast motions where we get it in light and sound and in the sense of solid contact.

#### Story: The Universe Becomes Aware of Itself

The universe is a system which is aware of itself.

We, as living organisms, are forms of the energy of the universe just as much as the stars and the galaxies.

And through our sense organs, this system of energy becomes aware of itself.

But the aspect of the universe which is aware of itself—the aspect which does the awareness—does not see itself.

#### Story: You Cannot Look at Your Eyes With Your Eyes

You can’t look at your eyes with your eyes.

You can’t kiss your own lips.

You can’t bite your own teeth.

You can’t observe yourself in the act of observing.

That therefore creates, on the backside of all observation, a blank spot.

That’s the unknown. That’s the part of the universe which does not see itself because it is seeing.

#### Story: The Unknowable Half of Experience

We always get this division of experience into one half known, one half unknown.

We would like, of course—it would be fascinating—if we could know the always unknown.

But if we examine the brain and the structure of the nerves behind the eyes, we’re always looking at somebody else’s brain out there.

We’re never looking at our own brain at the same time as we’re investigating somebody else’s brain.

So there always remains this blank side of experience.

#### Story: The Unconscious as the Background of Consciousness

The blank side of experience has the same relationship to the conscious side as the off principle of vibration has to the on principle.

The Chinese call them the positive side, the yang, and the negative side, the yin.

That corresponds to the idea of one in our language, and zero.

All numbers can be made of one and zero. That’s called binary arithmetic, which is used for computers.

And so it’s all made up of off and on, and therefore equally of conscious and unconscious.

But the unconscious is, so to say, the part of experience which is doing consciousness, just as the trough manifests the wave, the space manifests the solid, the background manifests the figure.

#### Story: The Deepest You Is the Side You Cannot Know

The deepest you is the nothing side. It is the side which you don’t know.

So, in this sense, don’t be afraid of nothing.

I could make a joke and say there’s nothing in nothing to be afraid of.

